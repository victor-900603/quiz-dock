function question(
  id: string,
  number: number,
  topic: string,
  prompt: string,
  options: Array<[string, string]>,
  correctAnswers: string[],
  explanation: string,
): Question {
  return {
    id,
    number,
    topic,
    prompt,
    options: options.map(([key, text]) => ({ key, text })),
    correctAnswers,
    explanation,
  }
}

function topicCount(setId: string): number {
  return new Set((mockQuestionsBySet[setId] ?? []).map((item) => item.topic)).size
}

